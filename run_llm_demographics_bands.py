"""
Demographics-only ranking with shuffled candidates, for ranks 1-20, 81-100 and 181-200.

Reuses the demographic descriptions already generated by run_llm_demographics.py (by GPT-6
Luna and by GPT-4o) for the users of the ranks 81-100 LLM sample, and repeats only the
ranking step with GPT-6 Luna. For each user and band the candidates are put in one random
order, used for all rankings of that user:

    baseline  - no user information
    luna      - GPT-6 Luna's demographic description
    gpt-4o    - GPT-4o's demographic description
    k12/25/50 - the names of 12, 25 or 50 accounts the user follows (the Table C prompts,
                with every account of the band's category lists removed)

so differences between them come from the user information alone. Bands:

    1-20      - the most popular candidates of the original sheets (sampled users who
                follow at least one of them)
    81-100    - the original sheets ranked by follower count (all sampled users)
    181-200   - the extended lists ranked by SocialVec popularity (sampled users who
                follow at least one of these candidates)

    python run_llm_demographics_bands.py --budget 0.6

Per-user scores go to results/llm/demographics_bands_per_user.csv.gz (no descriptions or usernames).
"""

import argparse
import json
import random
from concurrent.futures import ThreadPoolExecutor

import pandas as pd
from tqdm import tqdm

from reproduction.config import DATA_DIR, RESULTS_DIR, SEED
from reproduction.data import load_categories, load_users
from reproduction.llm import (
    ResponseCache,
    SpendingCap,
    candidates_json,
    llm_average_precision,
    load_openai_key,
    make_dspy_rankers,
    ranked_ids,
    user_prompts,
)
from reproduction.embeddings import load_metadata
from reproduction.llm_demographics import PROMPT_VERSION, make_demographic_programs
from run_llm_experiments import band_sample, band_setup

OUT = RESULTS_DIR / "llm"
PRIVATE = DATA_DIR / "llm_demographics"
BANDS = {"1-20": ((1, 20, "original"), "popularity_band_1_20"),
         "81-100": ((81, 100, "original"), "popularity_band_81_100"),
         "181-200": ((181, 200, "extended"), "popularity_band_181_200_extended")}
DESCRIPTIONS = {"luna": PRIVATE / "descriptions.csv", "gpt-4o": PRIVATE / "descriptions_gpt-4o.csv"}


def shuffled_order(candidates, band, row):
    ids = [int(i) for i in candidates["twitter_user_id"]]
    random.Random(f"{SEED}:{band}:{row}").shuffle(ids)
    return ids


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model", default="gpt-6-luna")
    p.add_argument("--effort", default="low")
    p.add_argument("--budget", type=float, default=0.6, help="stop calling the model at this cost (USD)")
    p.add_argument("--workers", type=int, default=16)
    args = p.parse_args()

    categories = load_categories()
    users = load_users(categories)
    sample, _, _, _ = band_sample(users, categories)  # the users whose descriptions exist
    descriptions = {k: pd.read_csv(path).set_index("row")["description"] for k, path in DESCRIPTIONS.items()}

    import dspy
    lm = dspy.LM(f"openai/{args.model}", api_key=load_openai_key(), reasoning_effort=args.effort, cache=False, num_retries=8)
    cap = SpendingCap(lm, args.budget)
    _, rank, _ = make_demographic_programs(lm)
    rank_personal, rank_default = make_dspy_rankers(lm=lm)
    rank, rank_personal, rank_default = cap.guard(rank), cap.guard(rank_personal), cap.guard(rank_default)
    cache = ResponseCache(OUT / "cache" / "demographics_bands.jsonl")
    metadata = load_metadata()
    names = dict(zip(metadata["twitter_id"].astype(str), metadata["name"]))

    jobs = []  # (band, row, topic, candidates, order, relevant, followed-account prompts)
    for band, (spec, _) in BANDS.items():
        candidates, exclude, _ = band_setup(users, categories, spec)
        prompts = user_prompts(sample, categories, names, exclude=exclude)
        for row, user in sample.iterrows():
            topic = user["topic"]
            if topic not in candidates:
                continue
            ids = set(candidates[topic]["twitter_user_id"])
            relevant = [f for f in user["friends_ids"] if f in ids]
            if relevant:
                jobs.append((band, row, topic, candidates[topic], shuffled_order(candidates[topic], band, row), relevant,
                             prompts.loc[row]))

    def run(job):
        band, row, topic, cands, order, relevant, followed = job
        text = candidates_json(cands, order=order)
        tag = f"{PROMPT_VERSION}|{band}"
        out = {"baseline": cache.call(f"{tag}|baseline|{row}", lambda: rank_default(text))}
        for source, desc in descriptions.items():
            if source == "luna" and band == "1-20":  # added after the Luna descriptions were dropped from the reports
                continue
            out[source] =cache.call(f"{tag}|{source}|{row}", lambda d=desc[row]: rank(d, text))
        for k in (12, 25, 50):
            out[f"k{k}"] = cache.call(f"{tag}|k{k}|{row}", lambda f=followed[f"llm_k{k}"]: rank_personal(f, text))
        return job, out

    try:
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            results = list(tqdm(pool.map(run, jobs), total=len(jobs), desc="Shuffled demographic rankings"))
    finally:
        cap.update()
        info_path = OUT / "run_info.json"
        runs = json.loads(info_path.read_text()) if info_path.exists() else []
        if cap.calls:
            runs.append({"model": args.model, "reasoning_effort": args.effort, "parts": ["demographics-bands"],
                         "calls": cap.calls, "cost_usd": round(cap.spent, 4), "budget_usd": args.budget})
            info_path.write_text(json.dumps(runs, indent=2))
        print(f"{cap.calls} model calls, ${cap.spent:.4f}")

    rows = []
    for (band, row, topic, cands, order, relevant, _), out in results:
        r = {"user": row, "topic": topic, "band": band, "n_relevant": len(relevant), "n_candidates": len(order),
             "order": json.dumps(order)}
        for kind, response in out.items():
            r[f"ap_{kind}"] = llm_average_precision(response, relevant)
            r[f"returned_{kind}"] = len(set(ranked_ids(response)) & set(order))
            r[f"resp_{kind}"] = response
        rows.append(r)
    res = pd.DataFrame(rows)

    # same users' scores under the other methods for each band
    merged = []
    for band, (_, folder) in BANDS.items():
        other = pd.read_csv(RESULTS_DIR / folder / "per_user_ap.csv.gz")
        other = other[(other["population"] == "category") & (other["candidates"] == "band")
                      & (other["exclusion"] == "exclude_category")][["user", "random", "popularity", "socialvec"]]
        merged.append(res[res["band"] == band].merge(other, on="user", how="left"))
    res = pd.concat(merged, ignore_index=True)
    prior = pd.read_csv(OUT / "band_per_user.csv.gz")[["user", "llm_baseline", "llm_k12", "llm_k25", "llm_k50",
                                                       "socialvec_k12", "socialvec_k25"]]
    d_luna = pd.read_csv(OUT / "demographics_per_user.csv.gz")[["user", "llm_demographics"]]
    d_4o = pd.read_csv(OUT / "demographics_per_user_gpt-4o.csv.gz")[["user", "llm_demographics"]].rename(
        columns={"llm_demographics": "llm_demographics_4o"})
    ordered = prior.merge(d_luna, on="user").merge(d_4o, on="user").rename(columns=lambda c: c if c == "user" else f"ordered_{c}")
    res = res.merge(ordered, on="user", how="left")
    for c in [c for c in res.columns if c.startswith("ordered_")]:
        res.loc[res["band"] != "81-100", c] = float("nan")  # the popularity-ordered runs exist for ranks 81-100 only
    res.to_csv(OUT / "demographics_bands_per_user.csv.gz", index=False)

    summary = res.groupby(["band", "topic"])[["random", "popularity", "socialvec", "ap_baseline", "ap_luna", "ap_gpt-4o", "ap_k12", "ap_k25", "ap_k50"]].mean()
    overall = summary.groupby("band").mean()
    overall["users"] = res.groupby("band").size()
    print(overall.round(3).to_string())


if __name__ == "__main__":
    main()
